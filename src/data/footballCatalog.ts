export function getCategoryById(id: string): FootballCategory {
  return ALL_CATEGORIES.find((c) => c.id === id) || ALL_CATEGORIES[0];
}

export function getCategoryForLevel(levelNumber: number): FootballCategory {
  const clamped = Math.max(1, Math.min(10, levelNumber));
  return ALL_CATEGORIES.find((c) => c.levelNumber === clamped) || ALL_CATEGORIES[0];
}

export function getRandomCategory(): FootballCategory {
  const index = Math.floor(Math.random() * ALL_CATEGORIES.length);
  return ALL_CATEGORIES[index];
}

export function getDailyCategory(): FootballCategory {
  const day = Math.floor(Date.now() / (1000 * 60 * 60 * 24));
  const index = day % ALL_CATEGORIES.length;
  return ALL_CATEGORIES[index];
}
